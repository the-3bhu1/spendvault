export interface OpaqueBounds {
  minX: number;
  minY: number;
  maxX: number;
  maxY: number;
}

export function opaqueBounds(rgba: ArrayLike<number>, width: number, height: number, alphaFloor: number): OpaqueBounds | null {
  let minX = width, minY = height, maxX = -1, maxY = -1;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (rgba[(y * width + x) * 4 + 3] > alphaFloor) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  return maxX < 0 ? null : { minX, minY, maxX, maxY };
}
